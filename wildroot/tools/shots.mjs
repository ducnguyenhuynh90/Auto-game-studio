// Visual QA: node wildroot/tools/shots.mjs (after a build). Serves wildroot/dist on :4180,
// plays lesson 1 and lesson 2 on desktop and phone, saves screenshots, prints any errors.
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { mkdirSync, rmSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium, devices } = require('playwright');
const out = 'wildroot/shots';
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const srv = spawn('npx', ['vite', 'preview', '--config', 'wildroot/vite.config.ts', '--port', '4180', '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [];
for (const [name, opts] of [['desktop', { viewport: { width: 1280, height: 800 } }], ['phone', { ...devices['iPhone 13'] }]]) {
  const ctx = await browser.newContext(opts);
  const page = await ctx.newPage();
  page.on('pageerror', (e) => errors.push(`${name}: ${e.message}`));
  page.on('console', (m) => m.type() === 'error' && errors.push(`${name}: ${m.text()}`));
  const shot = (n) => page.screenshot({ path: `${out}/${name}-${n}.png` });
  const f = { force: true };
  await page.goto('http://localhost:4180/');
  await page.waitForTimeout(1200);
  await page.click('#start');
  await page.waitForTimeout(500);
  await shot('1-intro-watch');
  await page.click('[data-do="begin"]');
  await page.waitForTimeout(300);
  await shot('2-watch-plan');
  await page.click('#go', f);
  await page.click('#fast', f);
  await page.waitForTimeout(2500);
  await shot('3-watch-running');
  await page.waitForTimeout(2500);
  await shot('4-watch-ask');
  await page.click('[data-chip="frogs"]', f);
  await page.waitForTimeout(400);
  await shot('5-watch-why');
  await page.click('[data-do="close"]');
  await page.waitForTimeout(600);
  await shot('6-watch-result');
  await page.click('[data-do="next"]');
  await page.waitForTimeout(500);
  await shot('7-intro-hide');
  await page.click('[data-do="begin"]');
  await page.waitForTimeout(900);
  await shot('8-hide-plan');
  await page.click('[data-card="reeds"]', f);
  const c = await page.evaluate(() => window.__wrTest.center());
  await page.mouse.click(c.x, c.y);
  await page.waitForTimeout(800);
  await page.click('#go', f);
  await page.click('#fast', f);
  await page.waitForTimeout(8000);
  await shot('9-hide-result');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) errors.push(`${name}: horizontal overflow`);
  await ctx.close();
}
await browser.close();
srv.kill();
console.log(errors.length ? errors.join('\n') : 'no errors');
